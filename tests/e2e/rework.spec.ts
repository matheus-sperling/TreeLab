import { expect, test } from '@playwright/test'

test('começar do zero, editar, reordenar e excluir operações', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Navegação principal' })).not.toContainText('Treinar')
  await page.getByRole('link', { name: /Criar minha árvore/ }).click()
  await expect(page.locator('.tree-svg')).toHaveAttribute('aria-label', /Árvore vazia/)
  const input = page.getByRole('textbox', { name: 'Valor ou lista de inteiros' })
  await input.click(); await input.pressSequentially('30,20,10')
  await page.getByRole('button', { name: 'Inserir valores' }).click()
  await page.getByRole('button', { name: 'Editar sequência' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('spinbutton', { name: 'Valor da operação 2' }).fill('25')
  await page.getByRole('spinbutton', { name: 'Valor da operação 2' }).press('Tab')
  await expect(page.getByRole('spinbutton', { name: 'Valor da operação 2' })).toHaveValue('25')
  await page.getByRole('button', { name: 'Mover operação 2 para antes' }).click()
  await expect(page.getByRole('spinbutton', { name: 'Valor da operação 1' })).toHaveValue('25')
  await page.getByRole('combobox', { name: 'Tipo da operação 2' }).selectOption('d')
  await page.getByRole('button', { name: 'Excluir operação 3' }).click()
  await expect(page.locator('.sequence-editor li')).toHaveCount(2)
  await page.getByRole('button', { name: 'Limpar sequência', exact: true }).click()
  await expect(page.locator('.tree-svg')).toHaveAttribute('aria-label', /Árvore vazia/)
})

test('semente atualiza imediatamente e opções persistem após reabrir e recarregar', async ({ page }) => {
  await page.goto('/lab?q=')
  await page.getByRole('button', { name: 'Abrir menu do laboratório' }).click()
  await page.getByRole('spinbutton', { name: 'Semente do laboratório' }).fill('73')
  await expect.poll(() => new URL(page.url()).searchParams.get('q')).not.toBe('')
  const first = await page.locator('.sequence-editor input').first().inputValue()
  await page.getByRole('spinbutton', { name: 'Semente do laboratório' }).fill('74')
  await expect(page.locator('.sequence-editor input').first()).not.toHaveValue(first)
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect.poll(() => new URL(page.url()).searchParams.get('q')).not.toBe('')
  const latestFirst = await page.locator('.sequence-editor input').first().inputValue()
  await page.getByRole('button', { name: 'Opções', exact: true }).click()
  await page.getByRole('switch', { name: 'Alturas dos nós' }).click()
  await page.getByRole('button', { name: 'Fechar painel' }).click()
  await page.getByRole('button', { name: 'Abrir menu do laboratório' }).click()
  await expect(page.getByRole('button', { name: 'Opções', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await page.getByRole('button', { name: 'Abrir menu do laboratório' }).click()
  await expect(page.getByRole('switch', { name: 'Alturas dos nós' })).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('button', { name: 'Minha árvore', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Semente do laboratório' })).toHaveValue('74')
  await expect(page.locator('.sequence-editor input').first()).toHaveValue(latestFirst)
})

test('exemplos e comparação abrem no início; mudar semente muda a comparação', async ({ page }) => {
  await page.goto('/')
  await page.locator('.lab-examples a').first().click()
  await expect(page.locator('.tree-svg')).toHaveAttribute('aria-label', /Árvore vazia/)
  await expect.poll(() => new URL(page.url()).searchParams.get('c')).toBe('0')
  await page.goto('/comparar')
  await page.getByRole('spinbutton', { name: 'Semente da sequência aleatória' }).fill('88')
  await expect(page.locator('.experiment-name')).toHaveText('Aleatória · semente 88')
  const ops = await page.locator('.compare-operation-chips').textContent()
  await page.getByRole('spinbutton', { name: 'Semente da sequência aleatória' }).fill('89')
  await expect(page.locator('.compare-operation-chips')).not.toHaveText(ops!)
  await page.locator('.comparison-card').first().click()
  await expect(page.locator('.tree-svg')).toHaveAttribute('aria-label', /Árvore vazia/)
})

test('teclado e reprodução cabem na área visível em telas curtas', async ({ page }) => {
  for (const size of [{ width: 393, height: 680 }, { width: 360, height: 640 }, { width: 412, height: 740 }, { width: 915, height: 412 }]) {
    await page.setViewportSize(size)
    await page.goto('/lab?q=i30.i20.i10')
    await page.getByRole('textbox', { name: 'Valor ou lista de inteiros' }).click()
    const button = page.getByRole('button', { name: 'Inserir valores' })
    await expect.poll(() => button.evaluate(el => { const b = el.getBoundingClientRect(); return b.bottom <= innerHeight - 16 && b.top >= 0 })).toBe(true)
    await page.getByRole('button', { name: 'Recolher teclado' }).click()
    const play = page.getByRole('button', { name: 'Reproduzir', exact: true })
    await expect(play).toBeVisible()
    expect(await play.evaluate(el => { const b = el.getBoundingClientRect(); return document.elementFromPoint(b.x + b.width / 2, b.y + b.height / 2)?.closest('button') === el })).toBe(true)
    await page.screenshot({ path: `docs/screenshots/rework-lab-${size.width}x${size.height}.png` })
  }
})

test('detalhes explicam a regra corrigida e recoloração mostra o motivo', async ({ page }) => {
  const { decodeOps, runSequence } = await import('../../app/engine')
  const avl = runSequence('avl', decodeOps('i30.i20.i10'))
  const rotation = avl.steps.findIndex(step => step.kind === 'rotate-pre')
  await page.goto(`/lab?t=avl&q=i30.i20.i10&c=${rotation}`)
  await expect(page.locator('.narration')).toContainText('dois níveis mais alto')
  await page.waitForTimeout(400) // Capture the settled animated scene.
  await page.screenshot({ path: 'docs/screenshots/rework-rotation.png' })
  await page.getByRole('button', { name: 'Detalhes', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Por que fazemos isso')
  await expect(page.locator('.reason-card')).toContainText('reduz essa diferença')
  await page.waitForTimeout(350) // Wait for the sheet entrance to complete.
  await page.screenshot({ path: 'docs/screenshots/rework-details.png' })
  const rb = runSequence('rb', decodeOps('i4.i2.i6.i1'))
  const recolor = rb.steps.findIndex(step => step.kind === 'recolor' && step.msg.params.reason?.toString().includes('tio'))
  await page.goto(`/lab?t=rb&q=i4.i2.i6.i1&c=${recolor}`)
  await expect(page.locator('.narration')).toContainText('→')
  await expect(page.locator('.narration')).toContainText('quantidade de pretos')
  await page.screenshot({ path: 'docs/screenshots/rework-recolor.png' })
})
